/** Keeps only the [label, value] pairs that actually have a value. */
export function pickSpecs(entries: [string, string | undefined][]): SpecEntry[] {
  return entries.filter((entry): entry is SpecEntry => Boolean(entry[1]))
}

export function getRelatedVessels(vessel: Vessel): Vessel[] {
  const all = orderedVessels
  if (vessel.brochureOrder <= 4) {
    return all.filter(
      (item) =>
        item.brochureOrder <= 4 && item.brochureOrder !== vessel.brochureOrder,
    )
  }

  const byProximity = (a: Vessel, b: Vessel) =>
    Math.abs(a.brochureOrder - vessel.brochureOrder) -
    Math.abs(b.brochureOrder - vessel.brochureOrder)
  const sameApplication = all
    .filter((item) => item.id !== vessel.id && item.category === vessel.category)
    .sort(byProximity)
  const nearby = all.filter((item) => item.id !== vessel.id).sort(byProximity)
  return [...sameApplication, ...nearby]
    .filter(
      (item, index, list) =>
        list.findIndex((candidate) => candidate.id === item.id) === index,
    )
    .slice(0, 3)
    .sort((a, b) => a.brochureOrder - b.brochureOrder)
}
